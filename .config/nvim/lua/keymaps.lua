-- ============================================================================
-- キーマッピング設定
-- ============================================================================

-- キーマッピング用のヘルパー関数
local function map(mode, lhs, rhs, opts)
  local options = { noremap = true, silent = true }
  if opts then
    options = vim.tbl_extend("force", options, opts)
  end
  vim.keymap.set(mode, lhs, rhs, options)
end

-- ============================================================================
-- リーダーキー設定
-- ============================================================================

-- スペースをリーダーキーに設定
vim.g.mapleader = " "
vim.g.maplocalleader = " "

-- ============================================================================
-- 一般的な操作
-- ============================================================================

-- 保存と終了
map("n", "<leader>w", ":w<CR>", { desc = "ファイルを保存" })
map("n", "<leader>q", ":q<CR>", { desc = "終了" })
map("n", "<leader>Q", ":qa!<CR>", { desc = "すべて強制終了" })

-- ESCの代替（Ctrl+c）
map("i", "<C-c>", "<Esc>")

-- 検索ハイライトをクリア
map("n", "<Esc>", ":noh<CR>", { desc = "検索ハイライトをクリア" })

-- 行の移動を表示行ベースに
map("n", "j", "gj")
map("n", "k", "gk")

-- ============================================================================
-- ウィンドウ操作
-- ============================================================================

-- ウィンドウ間の移動
map("n", "<C-h>", "<C-w>h", { desc = "左のウィンドウへ" })
map("n", "<C-j>", "<C-w>j", { desc = "下のウィンドウへ" })
map("n", "<C-k>", "<C-w>k", { desc = "上のウィンドウへ" })
map("n", "<C-l>", "<C-w>l", { desc = "右のウィンドウへ" })

-- ウィンドウのリサイズ
map("n", "<C-Up>", ":resize +2<CR>", { desc = "ウィンドウの高さを増やす" })
map("n", "<C-Down>", ":resize -2<CR>", { desc = "ウィンドウの高さを減らす" })
map("n", "<C-Left>", ":vertical resize -2<CR>", { desc = "ウィンドウの幅を減らす" })
map("n", "<C-Right>", ":vertical resize +2<CR>", { desc = "ウィンドウの幅を増やす" })

-- ウィンドウの分割
map("n", "<leader>sv", ":vsplit<CR>", { desc = "垂直分割" })
map("n", "<leader>sh", ":split<CR>", { desc = "水平分割" })
map("n", "<leader>se", "<C-w>=", { desc = "ウィンドウサイズを均等に" })
map("n", "<leader>sx", ":close<CR>", { desc = "現在のウィンドウを閉じる" })

-- ============================================================================
-- バッファ操作
-- ============================================================================

-- バッファの切り替え
map("n", "<S-h>", ":bprevious<CR>", { desc = "前のバッファへ" })
map("n", "<S-l>", ":bnext<CR>", { desc = "次のバッファへ" })

-- バッファを閉じる
map("n", "<leader>bd", ":bdelete<CR>", { desc = "現在のバッファを閉じる" })

-- すべてのバッファを閉じる（現在のバッファ以外）
map("n", "<leader>bo", ":%bd|e#|bd#<CR>", { desc = "他のバッファをすべて閉じる" })

-- ============================================================================
-- タブ操作
-- ============================================================================

-- タブの作成・移動
map("n", "<leader>tn", ":tabnew<CR>", { desc = "新しいタブ" })
map("n", "<leader>tc", ":tabclose<CR>", { desc = "タブを閉じる" })
map("n", "<leader>to", ":tabonly<CR>", { desc = "他のタブをすべて閉じる" })

-- タブの切り替え
map("n", "<leader>tp", ":tabprevious<CR>", { desc = "前のタブへ" })
map("n", "<leader>tn", ":tabnext<CR>", { desc = "次のタブへ" })

-- ============================================================================
-- テキスト編集
-- ============================================================================

-- インデント調整（ビジュアルモードで選択を維持）
map("v", "<", "<gv")
map("v", ">", ">gv")

-- 行の移動（ビジュアルモード）
map("v", "J", ":m '>+1<CR>gv=gv", { desc = "選択行を下に移動" })
map("v", "K", ":m '<-2<CR>gv=gv", { desc = "選択行を上に移動" })

-- 行の連結時にカーソル位置を維持
map("n", "J", "mzJ`z")

-- ページ移動時にカーソルを中央に
map("n", "<C-d>", "<C-d>zz")
map("n", "<C-u>", "<C-u>zz")

-- 検索時にカーソルを中央に
map("n", "n", "nzzzv")
map("n", "N", "Nzzzv")

-- ============================================================================
-- コピー・ペースト
-- ============================================================================

-- ペースト時にヤンクレジスタを維持（ビジュアルモード）
map("v", "p", '"_dP')

-- 削除時にレジスタに入れない
map("n", "x", '"_x')
map("n", "X", '"_X')

-- ============================================================================
-- ファイル操作
-- ============================================================================

-- Netrw（ファイルエクスプローラー）を開く
map("n", "<leader>e", ":Explore<CR>", { desc = "ファイルエクスプローラーを開く" })
map("n", "<leader>E", ":Vexplore<CR>", { desc = "垂直分割でエクスプローラーを開く" })

-- ============================================================================
-- クイックフィックス・ロケーションリスト
-- ============================================================================

-- クイックフィックスリストの操作
map("n", "<leader>co", ":copen<CR>", { desc = "クイックフィックスを開く" })
map("n", "<leader>cc", ":cclose<CR>", { desc = "クイックフィックスを閉じる" })
map("n", "[q", ":cprevious<CR>", { desc = "前のクイックフィックス" })
map("n", "]q", ":cnext<CR>", { desc = "次のクイックフィックス" })

-- ロケーションリストの操作
map("n", "<leader>lo", ":lopen<CR>", { desc = "ロケーションリストを開く" })
map("n", "<leader>lc", ":lclose<CR>", { desc = "ロケーションリストを閉じる" })
map("n", "[l", ":lprevious<CR>", { desc = "前のロケーション" })
map("n", "]l", ":lnext<CR>", { desc = "次のロケーション" })

-- ============================================================================
-- その他
-- ============================================================================

-- ターミナルモードでのキーマッピング
map("t", "<Esc>", "<C-\\><C-n>", { desc = "ターミナルモードから抜ける" })

-- 全選択
map("n", "<leader>a", "ggVG", { desc = "すべて選択" })

-- 行の先頭・末尾への移動
map("n", "H", "^", { desc = "行頭へ" })
map("n", "L", "$", { desc = "行末へ" })
map("v", "H", "^")
map("v", "L", "$")
